'use strict';

/* =============================================================================================
   In-browser replacement for the server API, used by the static (GitHub Pages) build.
   Same endpoints and response shapes as server/routes/*, with attempts kept in localStorage.
   Requires window.JTET_DATA (generated by scripts/build-static.js).
   ============================================================================================= */

(function () {
  const DATA = window.JTET_DATA;
  if (!DATA) return;

  const { config, questions, tests } = DATA;
  const STORE_KEY = 'jtet-mock.attempts.v1';
  const sectionById = Object.fromEntries(config.sections.map((s) => [s.id, s]));
  const testById = Object.fromEntries(tests.map((t) => [t.id, t]));
  let memoryStore = { nextId: 1, attempts: [] }; // used when localStorage is unavailable

  const httpError = (status, message) => Object.assign(new Error(message), { status });
  const needsLanguage1 = (t) => t.type === 'FULL' || t.sectionId === 'LANG1';
  const round1 = (n) => Math.round(n * 10) / 10;

  function load() {
    try {
      const raw = localStorage.getItem(STORE_KEY);
      return raw ? JSON.parse(raw) : { nextId: 1, attempts: [] };
    } catch {
      return memoryStore;
    }
  }
  function save(store) {
    memoryStore = store;
    try { localStorage.setItem(STORE_KEY, JSON.stringify(store)); } catch { /* keep in memory */ }
  }

  function sectionsSummary(answers) {
    const order = [];
    const counts = {};
    for (const a of answers) {
      if (!(a.section in counts)) order.push(a.section);
      counts[a.section] = (counts[a.section] || 0) + 1;
    }
    return order.map((id) => ({ id, name: sectionById[id]?.name, count: counts[id] }));
  }

  function finalize(a, submitType) {
    if (a.status === 'SUBMITTED') return a;
    let correct = 0, wrong = 0, skipped = 0;
    for (const ans of a.answers) {
      if (!ans.selected) { ans.isCorrect = null; skipped++; }
      else if (ans.selected === questions[ans.questionId].answer) { ans.isCorrect = 1; correct++; }
      else { ans.isCorrect = 0; wrong++; }
    }
    const now = Date.now();
    Object.assign(a, {
      status: 'SUBMITTED',
      submitType: now > a.endTime ? 'AUTO' : submitType,
      submittedAt: Math.min(now, a.endTime),
      score: correct * config.marking.correct + wrong * config.marking.wrong,
      correct, wrong, skipped,
    });
    return a;
  }

  // Auto-submit every attempt whose time is over (replaces the server's background job).
  function expireAll(store) {
    let changed = false;
    for (const a of store.attempts) {
      if (a.status === 'IN_PROGRESS' && Date.now() > a.endTime) { finalize(a, 'AUTO'); changed = true; }
    }
    if (changed) save(store);
  }

  function getAttempt(store, id) {
    const a = store.attempts.find((x) => x.id === Number(id));
    if (!a) throw httpError(404, 'Attempt not found.');
    return a;
  }

  function withStatus(store, t) {
    const mine = store.attempts.filter((a) => a.testId === t.id).sort((x, y) => y.id - x.id);
    const live = mine.find((a) => a.status === 'IN_PROGRESS' && a.endTime > Date.now());
    const last = mine.find((a) => a.status === 'SUBMITTED');
    return {
      id: t.id,
      title: t.title,
      type: t.type,
      sectionId: t.sectionId,
      durationMinutes: t.duration,
      totalQuestions: t.total,
      needsLanguage1: needsLanguage1(t),
      status: live ? 'IN_PROGRESS' : last ? 'COMPLETED' : 'NOT_ATTEMPTED',
      inProgressAttemptId: live?.id ?? null,
      lastAttempt: last ? { id: last.id, score: last.score, total: last.total } : null,
    };
  }

  const statusOf = (ans) => (ans.isCorrect === 1 ? 'CORRECT' : ans.isCorrect === 0 ? 'WRONG' : 'SKIPPED');

  // ---- endpoints ------------------------------------------------------------------------------

  const routes = [
    ['GET', /^\/config$/, () => ({
      title: config.title,
      marking: config.marking,
      fullMock: config.fullMock,
      sectional: config.sectional,
      cutoffs: config.cutoffs,
      timerWarningsMinutes: config.timerWarningsMinutes,
      timerRedZoneMinutes: config.timerRedZoneMinutes,
      sections: config.sections.map((s) => ({ id: s.id, name: s.name, questions: s.questions, marks: s.marks })),
    })],

    ['GET', /^\/tests$/, (store, m, body, query) => {
      const type = query.get('type');
      const section = query.get('section');
      const list = tests.filter((t) => (!type || t.type === type) && (!section || t.sectionId === section));
      return { tests: list.map((t) => withStatus(store, t)) };
    }],

    ['GET', /^\/tests\/(\d+)$/, (store, [, id]) => {
      const t = testById[id];
      if (!t) throw httpError(404, 'Test not found.');
      const groups = [];
      for (const qid of t.questionIds) {
        const q = questions[qid];
        let g = groups.find((x) => x.section === q.section && x.language === q.language);
        if (!g) groups.push(g = { section: q.section, language: q.language, count: 0 });
        g.count++;
      }
      const merged = [];
      for (const g of groups) {
        const existing = merged.find((x) => x.id === g.section);
        if (existing) existing.count = Math.max(existing.count, g.count);
        else merged.push({ id: g.section, name: sectionById[g.section]?.name, count: g.count });
      }
      return { test: { ...withStatus(store, t), sections: merged } };
    }],

    ['POST', /^\/attempts$/, (store, m, body) => {
      const t = testById[body.mockTestId];
      if (!t) throw httpError(404, 'Test not found.');
      if (needsLanguage1(t) && !['EN', 'HI'].includes(body.language1Choice)) {
        throw httpError(400, 'Choose Language-1 (English or Hindi).');
      }
      const live = store.attempts.find((a) => a.testId === t.id && a.status === 'IN_PROGRESS');
      if (live) return { attemptId: live.id, resumed: true };

      const choice = needsLanguage1(t) ? body.language1Choice : null;
      const qids = t.questionIds.filter((id) => questions[id].section !== 'LANG1' || questions[id].language === choice);
      if (!qids.length) throw httpError(400, 'This test has no questions yet.');
      const minutes = t.type === 'FULL' ? t.duration : Math.max(1, Math.round(config.sectional.minutesPerQuestion * qids.length));
      const start = Date.now();
      const attempt = {
        id: store.nextId++,
        testId: t.id,
        title: t.title,
        type: t.type,
        sectionId: t.sectionId,
        language1Choice: choice,
        status: 'IN_PROGRESS',
        startTime: start,
        endTime: start + minutes * 60_000,
        total: qids.length,
        answers: qids.map((id, i) => ({
          questionId: id, no: i + 1, section: questions[id].section,
          selected: null, marked: false, visited: false, timeSeconds: 0, isCorrect: null,
        })),
      };
      store.attempts.push(attempt);
      save(store);
      return { attemptId: attempt.id, resumed: false };
    }],

    ['GET', /^\/attempts\/(\d+)$/, (store, [, id]) => {
      const a = getAttempt(store, id);
      if (a.status === 'SUBMITTED') return { id: a.id, status: 'SUBMITTED' };
      const now = Date.now();
      return {
        id: a.id,
        status: a.status,
        test: { id: a.testId, title: a.title, type: a.type, sectionId: a.sectionId },
        candidateName: 'Candidate',
        language1Choice: a.language1Choice,
        serverNow: now,
        endTime: a.endTime,
        remainingSeconds: Math.max(0, Math.floor((a.endTime - now) / 1000)),
        sections: sectionsSummary(a.answers),
        questions: a.answers.map((ans) => {
          const q = questions[ans.questionId];
          return {
            id: q.id, no: ans.no, section: ans.section, question: q.question,
            options: q.options.map((o) => ({ ...o })),
            selected: ans.selected, marked: ans.marked, visited: ans.visited,
          };
        }),
      };
    }],

    ['PUT', /^\/attempts\/(\d+)\/answers$/, (store, [, id], body) => {
      const a = getAttempt(store, id);
      if (a.status === 'SUBMITTED') throw httpError(409, 'This attempt has already been submitted.');
      const ans = a.answers.find((x) => x.questionId === body.questionId);
      if (!ans) throw httpError(404, 'Question is not part of this attempt.');
      if (body.selectedOption !== undefined) {
        if (body.selectedOption !== null && !['A', 'B', 'C', 'D'].includes(body.selectedOption)) throw httpError(400, 'Invalid option.');
        ans.selected = body.selectedOption;
      }
      if (body.markedForReview !== undefined) ans.marked = !!body.markedForReview;
      if (body.timeSpentSeconds) ans.timeSeconds += Math.min(3600, Math.max(0, Math.round(body.timeSpentSeconds)));
      ans.visited = true;
      save(store);
      return { ok: true };
    }],

    ['POST', /^\/attempts\/(\d+)\/submit$/, (store, [, id]) => {
      const a = finalize(getAttempt(store, id), 'MANUAL');
      save(store);
      return { ok: true, status: a.status, submitType: a.submitType };
    }],

    ['GET', /^\/attempts\/(\d+)\/result$/, (store, [, id]) => {
      const a = getAttempt(store, id);
      if (a.status !== 'SUBMITTED') throw httpError(403, 'Submit the test to unlock results and solutions.');
      const sections = sectionsSummary(a.answers).map((s) => {
        const list = a.answers.filter((x) => x.section === s.id);
        const correct = list.filter((x) => x.isCorrect === 1).length;
        const wrong = list.filter((x) => x.isCorrect === 0).length;
        const attempted = correct + wrong;
        return {
          ...s, attempted, correct, wrong,
          skipped: list.length - attempted,
          score: correct * config.marking.correct + wrong * config.marking.wrong,
          maxMarks: list.length * config.marking.correct,
          accuracy: attempted ? round1((correct / attempted) * 100) : 0,
          timeSeconds: list.reduce((t, x) => t + x.timeSeconds, 0),
        };
      });
      const maxMarks = a.total * config.marking.correct;
      const percentage = maxMarks ? round1((a.score / maxMarks) * 100) : 0;
      return {
        id: a.id,
        test: { title: a.title, type: a.type, sectionId: a.sectionId },
        language1Choice: a.language1Choice,
        score: a.score, maxMarks, percentage,
        correct: a.correct, wrong: a.wrong, skipped: a.skipped, total: a.total,
        startedAt: a.startTime, submittedAt: a.submittedAt, submitType: a.submitType,
        timeTakenSeconds: Math.round((a.submittedAt - a.startTime) / 1000),
        durationSeconds: Math.round((a.endTime - a.startTime) / 1000),
        cutoffs: Object.entries(config.cutoffs).map(([category, cutoff]) => ({ category, cutoff, qualified: percentage >= cutoff })),
        sections,
        slowest: a.answers.filter((x) => x.timeSeconds > 0)
          .sort((x, y) => y.timeSeconds - x.timeSeconds).slice(0, 5)
          .map((x) => ({ no: x.no, section: x.section, topic: questions[x.questionId].topic, timeSeconds: x.timeSeconds, status: statusOf(x) })),
      };
    }],

    ['GET', /^\/attempts\/(\d+)\/solutions$/, (store, [, id]) => {
      const a = getAttempt(store, id);
      if (a.status !== 'SUBMITTED') throw httpError(403, 'Submit the test to unlock results and solutions.');
      return {
        id: a.id,
        test: { title: a.title },
        score: a.score,
        total: a.total,
        sections: sectionsSummary(a.answers),
        questions: a.answers.map((x) => {
          const q = questions[x.questionId];
          return {
            id: q.id, no: x.no, section: x.section, topic: q.topic,
            question: q.question, options: q.options, answer: q.answer, explanation: q.explanation,
            selected: x.selected, marked: x.marked, status: statusOf(x), timeSeconds: x.timeSeconds,
          };
        }),
      };
    }],

    ['GET', /^\/me\/attempts$/, (store) => {
      const list = [...store.attempts].sort((x, y) => y.startTime - x.startTime);
      const submitted = list.filter((a) => a.status === 'SUBMITTED');
      const pct = (a) => (a.total ? (a.score / (a.total * config.marking.correct)) * 100 : 0);
      return {
        stats: {
          attempted: submitted.length,
          bestPercentage: submitted.length ? round1(Math.max(...submitted.map(pct))) : null,
          averagePercentage: submitted.length ? round1(submitted.reduce((t, a) => t + pct(a), 0) / submitted.length) : null,
        },
        attempts: list.map((a) => ({
          id: a.id, testId: a.testId, title: a.title, type: a.type, sectionId: a.sectionId,
          status: a.status, startedAt: a.startTime, submittedAt: a.submittedAt ?? null, submitType: a.submitType ?? null,
          score: a.score ?? null, total: a.total,
          timeTakenSeconds: a.submittedAt ? Math.round((a.submittedAt - a.startTime) / 1000) : null,
        })),
      };
    }],
  ];

  async function call(path, { method = 'GET', body } = {}) {
    const [pathname, search = ''] = path.split('?');
    const route = routes.find(([m, re]) => m === method && re.test(pathname));
    if (!route) throw httpError(404, 'Not found.');
    const store = load();
    expireAll(store);
    const result = route[2](store, pathname.match(route[1]), body || {}, new URLSearchParams(search));
    return JSON.parse(JSON.stringify(result)); // callers get their own copy, like a network response
  }

  window.LocalApi = { call };
})();
