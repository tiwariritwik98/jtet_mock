// Builds the static (no server) version of the portal into dist/ for GitHub Pages.
// The question bank and tests are embedded in dist/data.js; attempts live in each browser's localStorage.
// Note: in this build the answer keys ship to the browser (unavoidable without a server).
const fs = require('node:fs');
const path = require('node:path');
const { pattern } = require('../server/config');
const { loadBank, planTests } = require('../server/lib/bank');

const ROOT = path.join(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const OUT = path.resolve(process.argv[2] || path.join(ROOT, 'dist'));

const bank = loadBank();
const tests = planTests(bank).map((t, i) => ({
  id: i + 1,
  slug: t.slug,
  title: t.title,
  type: t.type,
  sectionId: t.sectionId,
  duration: t.duration,
  total: t.total,
  questionIds: t.questions.map((q) => q.id),
}));
const questions = Object.fromEntries(bank.map((q) => [q.id, {
  id: q.id, section: q.section, language: q.language || null, topic: q.topic || null,
  question: q.question, options: q.options, answer: q.answer, explanation: q.explanation,
}]));

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'data.js'),
  `// Generated by scripts/build-static.js — do not edit. Edit data/questions/*.json and rebuild.\n` +
  `window.JTET_DATA = ${JSON.stringify({ config: pattern, questions, tests })};\n`);

for (const file of ['app.js', 'local-api.js', 'styles.css']) {
  fs.copyFileSync(path.join(PUBLIC, file), path.join(OUT, file));
}

const html = fs.readFileSync(path.join(PUBLIC, 'index.html'), 'utf8')
  .replace('<script src="app.js"></script>',
    '<script src="data.js"></script>\n  <script src="local-api.js"></script>\n  <script src="app.js"></script>');
if (!html.includes('local-api.js')) throw new Error('Could not find the app.js script tag in public/index.html');
fs.writeFileSync(path.join(OUT, 'index.html'), html);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
fs.writeFileSync(path.join(OUT, 'README.md'), `# JTET Level 2 Mock Tests

Free practice mock tests for **JTET Paper II / Level 2 (Class 6–8)**: a Full Mock (${pattern.fullMock.totalQuestions} questions, ${pattern.fullMock.durationMinutes} minutes) and Sectional Mocks, with results and step-by-step solutions after submission.

Runs entirely in the browser (GitHub Pages). No login; attempts are saved in each visitor's browser.

This repository is generated by \`npm run build:static\` from the main project. Edit the questions there and rebuild; do not edit these files by hand.

*Independent practice portal, not affiliated with the Jharkhand Academic Council (JAC).*
`);

console.log(`Static site built in ${OUT}`);
console.log(`  ${bank.length} questions, ${tests.length} tests`);
for (const t of tests) console.log(`  #${t.id} ${t.title}: ${t.total} questions, ${t.duration} min`);
